#!/usr/bin/env bash
# Builds two SQL files to paste into the Supabase SQL Editor:
#   supabase/.generated/setup.sql        create everything (fresh project)
#   supabase/.generated/reset-and-setup.sql  wipe all app data, then create everything
set -euo pipefail

cd "$(dirname "$0")/.."
out=supabase/.generated
mkdir -p "$out"

{
  echo "-- Generated by scripts/build-db-sql.sh. Do not edit; edit supabase/migrations instead."
  for f in supabase/migrations/*.sql; do
    printf '\n-- ===== %s =====\n' "$f"
    cat "$f"
  done
  printf '\n-- ===== supabase/seed.sql =====\n'
  cat supabase/seed.sql
} > "$out/setup.sql"

{
  echo "begin;"
  printf '\n-- ===== supabase/reset.sql =====\n'
  cat supabase/reset.sql
  printf '\n'
  cat "$out/setup.sql"
  printf '\ncommit;\n'
} > "$out/reset-and-setup.sql"

echo "Wrote $out/setup.sql and $out/reset-and-setup.sql"
